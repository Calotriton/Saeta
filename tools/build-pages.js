// Builds the static pages from src/layout.html + src/pages/*.html.
// Usage: node tools/build-pages.js
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const read = f => fs.readFileSync(path.join(root, f), 'utf8');

// Spanish strings are the default (pre-JS) text of every page
global.window = {};
eval(read('js/i18n.js'));
const ES = window.I18N.es;

const PAGES = [
  { file: 'index.html', src: 'home.html', page: 'home', title: ES['meta.title'], description: 'Saeta: guía interactiva para construir flechas de arquería tradicional. Elige componentes, calcula longitud, spine y pesos, mira tu flecha en 2D/3D y encuentra tiendas europeas.' },
  { file: 'constructor.html', src: 'constructor.html', page: 'builder', description: 'Constructor de flechas: elige arco, material, punta, culatín y plumas, y calcula longitud, spine, peso, GPP y FOC.' },
  { file: 'carcaj.html', src: 'carcaj.html', page: 'quiver', description: 'Tu galería de flechas guardadas, tiendas favoritas y preferencias, sin registrarte.' },
  { file: 'guia.html', src: 'guia.html', page: 'guide', description: 'Cómo fabricar flechas de madera, bambú, carbono, fibra de vidrio y aluminio: herramientas, pasos, seguridad y tutorial 3D.' },
  { file: 'tiendas.html', src: 'tiendas.html', page: 'shops', description: 'Directorio de tiendas europeas con material para fabricar flechas de arquería tradicional.' },
  { file: 'glosario.html', src: 'glosario.html', page: 'glossary', description: 'Glosario de arquería tradicional y fabricación de flechas (ES/EN).' },
  { file: 'acerca.html', src: 'acerca.html', page: 'about', description: 'Sobre Saeta y consejos de seguridad para fabricar y usar flechas.' },
];

const layout = read('src/layout.html').replace(/^<!--[^\n]*-->\n/, '');
for (const p of PAGES) {
  const title = p.title || `${ES['page.' + p.page]} · Saeta`;
  let html = layout
    .split('{{title}}').join(title)
    .split('{{description}}').join(p.description)
    .split('{{page}}').join(p.page)
    .replace('{{content}}', read('src/pages/' + p.src));
  // highlight the current page in the navigation
  html = html.replace(`<a href="${p.file}"`, `<a href="${p.file}" aria-current="page"`);
  const banner = `<!-- Generated by tools/build-pages.js from src/ — do not edit directly. -->\n`;
  fs.writeFileSync(path.join(root, p.file), html.replace('<!doctype html>\n', '<!doctype html>\n' + banner));
  console.log('wrote', p.file);
}
